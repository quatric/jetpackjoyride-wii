#!/usr/bin/env python3 -I
"""Vehicle head placement (VehicleXData.xml, default skin only) -> C header: {dx,dy,headFrame,rotation deg} per vehicle frame.
usage: mkvhead.py out.h MechData.xml HogData.xml ..."""
import sys, re
out = ['/* generated by tools/mkvhead.py */']
for i, f in enumerate(sys.argv[2:]):
    t = open(f).read().split('<skin')[0]
    fr = {int(m[0]): (int(m[1]), int(m[2]), int(m[4]), int(m[3])) for m in re.findall(r'<frame value="(\d+)" offset="(-?\d+),(-?\d+)" rotation="(-?\d+)"[^>]*headFrame="(\d+)"', t)}
    n = max(fr) + 1
    for k in range(2, n):   # sparse files (bird) only list some frames: reuse the nearest lower one
        fr.setdefault(k, fr.get(k - 1, (0, 0, 5, 0)))
    out.append('static const short VHEAD%d[%d][4] = {%s};' % (i, n, ','.join('{%d,%d,%d,%d}' % fr.get(k, (0, 0, 5, 0)) for k in range(n))))
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
